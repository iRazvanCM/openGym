// Everyday foods for the food diary, per 100 g (drinks per 100 ml), so the basics — chicken,
// rice, eggs, oats — are one tap away without a barcode or a connection, in the way they are
// eaten: raw for weighing before cooking, and boiled, oven-baked, air-fried, pan-fried or grilled
// for weighing on the plate. Packaged food comes from a barcode or an Open Food Facts search
// instead (lib/off.js), where the label's own numbers are better than any average.
//
// Values are the usual reference figures (USDA FoodData Central, rounded); a product on the
// shelf can differ by a few percent. Cooked meat and fish weigh less than raw (water lost), so
// the same piece has more per 100 g once cooked: 100 g of raw chicken breast is about 75 g
// roasted. "Pan" and "fried" include the oil a normal pan or fryer leaves on the food; "air
// fryer" a light spray. Home dishes (sarmale, ciorbă, shaorma) are typical recipes: a good
// average, not a label — weigh the plate and pick the closest one.
//
// Each row: id, ro / en names, kcal, protein, carbs, fat, then optional `fib` (fibre), `unit`
// ('ml' for drinks) and a typical `serving`. Ids never change: a diary item keeps pointing at
// its food by id (lib/food.js foodFor), so a row may be renamed or corrected but not re-keyed.

